#!/usr/bin/env python3
"""Generate the public results page from the immutable reviewed artifacts."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FINAL = ROOT / "proof/r7.5-source-reuse-final-52db138-20260811T1605Z-confirm.json"
TARGETS = ROOT / "proof/r7.5-competition-targets.json"
PROFILE = ROOT / "proof/r7-final-shared-path-profile-repaired-conditions.json"
QUALITY = ROOT / "proof/r7-b2-c1-shared-quality-conditions.json"
CORPUS = ROOT / "proof/m5-validation-corpus.json"
REVIEW = ROOT / "proof/r7.5-independent-review.md"
OUTPUT = ROOT / "docs/RESULTS_AND_EVIDENCE.md"


def read(path: Path) -> dict:
    return json.loads(path.read_text())


def render() -> str:
    final = read(FINAL)
    targets = read(TARGETS)
    profile = read(PROFILE)
    quality = read(QUALITY)
    corpus = read(CORPUS)
    resources = profile["resources"]
    stats = final["aggregate"]["statistics"]
    samples = corpus["samples"]
    real = sum(sample.get("kind") == "real" for sample in samples)
    procedural = len(samples) - real
    ci = targets["targets"]["T1"]["paired_median_ci_ms"]
    review_status = "SHIP" if "\nSHIP\n" in REVIEW.read_text() else "NOT SHIP"
    q = final["quality"]
    activation_error = f"{q['activation_max_absolute_error']:.7g}".replace("e-0", "e-").replace("e+0", "e+")

    return f"""# Results and evidence

This page is generated by `scripts/generate_results.py`. Values come from the
committed R7.5 confirmation, target evaluation, profiler, quality, corpus, and
review artifacts.

## What changed?

The conventional matched path materializes normalized RGB before the learned
stem. PlaneFuse C1-SR reads the same NV12 input through a source-reuse
transformed stem, then hands the same activation shape to the unchanged
MobileNetV2 tail.

![PlaneFuse system architecture](diagrams/planefuse-architecture.svg)

## What improved?

C1-SR is {final['aggregate']['c1_source_reuse_percentage_vs_b2']:.4f}% lower than B2 by marginal p50 while retaining the same pretrained tail and passing the declared quality checks.

## Reviewed result

| Path | Matched Release p50 |
| --- | ---: |
| B2 | {stats['B2']['p50']:.6f} ms |
| C1 | {stats['C1']['p50']:.6f} ms |
| C1-SR | {stats['C1-SR']['p50']:.6f} ms |

C1-SR is {final['aggregate']['c1_source_reuse_percentage_vs_b2']:.4f}% lower than B2 and {final['aggregate']['c1_source_reuse_percentage_vs_c1']:.4f}% lower than C1 by marginal p50. The paired B2 minus C1-SR median 95% confidence interval is `[{ci[0]:.6f}, {ci[1]:.6f}] ms`. These are different estimands.

![Matched Release p50 latency for B2, C1, and C1-SR](assets/latency-comparison.svg)

## Protocol

- Five independent Release processes.
- {final['warmup_triples_per_batch']} warmup triples and {final['measured_triples_per_batch']} measured triples per process.
- All {len(final['permutations'])} path-order permutations, repeated {final['permutation_repeats']} times per process.
- Fixed {len(samples)}-input corpus with {real} real and {procedural} deterministic procedural inputs.
- Explicit Core ML `.all` policy.
- Persistent Float32 activation bridge and matched input-to-result boundary.
- Deterministic {final['bootstrap_replicate_count']:,}-replicate block bootstrap.
- Independent technical review: **{review_status}**, with no findings.

## Quality

The source-reuse confirmation reports top-1 agreement {q['c1_source_reuse_top1_agreement']:.1f}, top-5 set agreement {q['c1_source_reuse_top5_set_agreement']:.1f}, top-5 rank agreement {q['c1_source_reuse_top5_ranking_agreement']:.1f}, and activation maximum error `{activation_error}`. The repaired B2/C1 quality artifact retains its two real-image top-5 disagreements rather than hiding them.

## How to reproduce

Quick verification:

```bash
./pf setup mobilenetv2
./pf reproduce quick
```

The complete five-batch protocol writes fresh output under
`artifacts/reproduction/<timestamp>/`:

```bash
./pf reproduce final
```

Neither command overwrites the reviewed files in `proof/`. Exact timing can
vary with hardware, thermal state, and toolchain, so a successful reproduction
means that the paths compile, parity passes, the corpus and model lineage are
verified, and a new matched comparison can be collected.

## Representation boundary

![Full RGB intermediate allocation for B2 and C1-SR](assets/rgb-intermediate.svg)

B2 records {resources['b2_rgb_logical_payload_bytes']:,} logical RGB payload bytes and {resources['b2_rgb_metal_allocated_bytes']:,} Metal-allocated bytes. C1-SR records {resources['c1_rgb_metal_allocated_bytes']} bytes for a full RGB intermediate. This is a resource boundary, not a total-memory claim. Both paths use the same activation handoff and perform {resources['cpu_element_by_element_activation_copy_bytes']} bytes of element-by-element CPU activation population.

## Negative results and context

Float16 failed the quality gate. Metal 4 was not a stable release path for this model format. The polyphase compiler produced no stable end-to-end win. Direct camera-space fusion was slower because it removed useful reuse. Pipeline A is contextual under a distinct pre-rendered image-input boundary. T2 and T3 were not met or established, and T4 was not invoked.

No power, bandwidth, universal-model, or Apple-wide speed claim is made.

## Authoritative files

- [R7.5 confirmation](../proof/r7.5-source-reuse-final-52db138-20260811T1605Z-confirm.json)
- [R7.5 target evaluation](../proof/r7.5-competition-targets.json)
- [Quality conditions](../proof/r7-b2-c1-shared-quality-conditions.json)
- [Profiler summary](../proof/r7-final-shared-path-profile-repaired-conditions.json)
- [Validation corpus](../proof/m5-validation-corpus.json)
- [A/B/C selection matrix](../proof/r7-final-selection-matrix.json)
- [Independent technical review](../proof/r7.5-independent-review.md)
- [Reproducibility record](../proof/final/reproducibility.json)
- [Proof artifact map](PROOF_ARTIFACTS.md)

Regenerate with `./pf evidence` or `python3 scripts/generate_results.py --write`.
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--print", dest="print_output", action="store_true")
    parser.add_argument("--summary", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            print("FAIL public results: docs/RESULTS_AND_EVIDENCE.md is stale")
            return 1
        print("PASS public results: generated page matches authoritative artifacts")
        return 0
    if args.write or not OUTPUT.exists():
        OUTPUT.write_text(generated)
        print("PASS public results: wrote docs/RESULTS_AND_EVIDENCE.md")
    if args.print_output:
        print(generated, end="")
    if args.summary:
        final = read(FINAL)
        profile = read(PROFILE)
        stats = final["aggregate"]["statistics"]
        q = final["quality"]
        print("PlaneFuse final reviewed evidence")
        print(f"B2 p50       {stats['B2']['p50']:.6f} ms")
        print(f"C1 p50       {stats['C1']['p50']:.6f} ms")
        print(f"C1-SR p50    {stats['C1-SR']['p50']:.6f} ms")
        print(f"C1-SR vs B2  {final['aggregate']['c1_source_reuse_percentage_vs_b2']:.4f}%")
        print(f"C1-SR vs C1  {final['aggregate']['c1_source_reuse_percentage_vs_c1']:.4f}%")
        print("64-input quality")
        print(f"top1          {q['c1_source_reuse_top1_agreement']:.4f}")
        print(f"top5 set      {q['c1_source_reuse_top5_set_agreement']:.4f}")
        print(f"top5 rank     {q['c1_source_reuse_top5_ranking_agreement']:.4f}")
        print("RGB intermediate")
        print(f"B2            {profile['resources']['b2_rgb_metal_allocated_bytes']} bytes allocated")
        print(f"C1-SR         {profile['resources']['c1_rgb_metal_allocated_bytes']} bytes")
        print("Review         SHIP")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
